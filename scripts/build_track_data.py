"""Generate compact, stdlib-only geometry from AGX's three public circuits.

Usage: python3 scripts/build_track_data.py /path/to/agx-racing-reference
Input: kit/data/*.mapdata.json and assets/*.json from AGX's official downloads.
Geometry derivatives retain the source ODbL 1.0 attribution; no private logs.
"""
import argparse
import hashlib
import json
from pathlib import Path

RUNTIME = '''
from bisect import bisect_right
import math

_STATIONS = {key: tuple(row[0] for row in data["rows"])
             for key, data in TRACKS.items()}


def _track(length):
    if type(length) not in (int, float) or not math.isfinite(length):
        return None
    closest = min(TRACKS.values(), key=lambda t: abs(t["length"] - length))
    # Circuit IDs are absent from some observations. Never guess an unknown map.
    return closest if abs(closest["length"] - length) < 2.0 else None


def geometry_at(track_length_m, s):
    """Return current (curvature, geometric grade, left width, right width).

    Interpolate the actual map station coordinates, including the lap seam.
    A small published-length mismatch is allowed; official_length is never used.
    """
    data = _track(track_length_m)
    if data is None or type(s) not in (int, float) or not math.isfinite(s):
        return None
    position = (s % track_length_m) % data["length"]
    rows, stations = data["rows"], _STATIONS[data["id"]]
    index = bisect_right(stations, position) - 1
    a = rows[index]
    b = rows[(index + 1) % len(rows)]
    end = b[0] if index + 1 < len(rows) else data["length"]
    fraction = (position - a[0]) / max(1e-9, end - a[0])
    return tuple(a[j] + fraction * (b[j] - a[j]) for j in range(1, 5))


def pit_distance(track_length_m, s):
    """Forward arc distance to pit entry, in the observed station coordinates."""
    data = _track(track_length_m)
    if data is None:
        return None
    return (data["pit_entry"] - s) % track_length_m


def aero_remaining(track_length_m, s):
    """Remaining distance in a public X-mode zone, or 0 / unknown None.

    Authoring stations have minor rounding differences from sampled geometry;
    the controller must keep a margin and the platform enforces mechanical gates.
    """
    data = _track(track_length_m)
    if data is None:
        return None
    position = s % track_length_m
    for start, end in data["aero_zones"]:
        span = (end - start) % track_length_m
        progress = (position - start) % track_length_m
        if progress < span:
            return span - progress
    return 0.0
'''


def build(source, output):
    source = Path(source)
    tracks, hashes = {}, {}
    for track in ('parkland', 'highland', 'crossover'):
        path = source / 'kit/data' / f'racing-{track}.mapdata.json'
        asset_path = source / 'assets' / f'{track}.json'
        raw, raw_asset = path.read_bytes(), asset_path.read_bytes()
        data, asset = json.loads(raw), json.loads(raw_asset)
        hashes[track] = {'mapdata_sha256': hashlib.sha256(raw).hexdigest(),
                         'asset_sha256': hashlib.sha256(raw_asset).hexdigest()}
        # Every third public ~2m sample: ~6m spacing. Keep the final sample.
        samples = data['centerline'][::3]
        if samples[-1] != data['centerline'][-1]:
            samples.append(data['centerline'][-1])
        columns = ('s_m', 'curvature_1pm', 'grade_dz_ds',
                   'half_width_left_m', 'half_width_right_m')
        precision = (4, 9, 7, 4, 4)
        rows = [tuple(round(row[key], digits) for key, digits in zip(columns, precision))
                for row in samples if row['s_m'] < data['length_m']]
        tracks[track] = {'id': track, 'length': data['length_m'],
                         'pit_entry': data['pit']['entry_s'],
                         'aero_zones': [(z['start_s'], z['end_s'])
                                        for z in asset['active_aero_zones']],
                         'rows': rows}
    header = ('"""Generated public AGX geometry. Do not hand-edit.\n'
              'Source: https://agx.cool/docs/schema/maps/racing.html\n'
              '© OpenStreetMap contributors · ODbL 1.0; Copernicus DEM / SRTM.\n'
              'Derived geometry database: ODbL 1.0 (see NOTICE.md).\n'
              'Generated by scripts/build_track_data.py; ~6m samples.\n"""\n')
    text = header + 'SOURCE_HASHES = ' + repr(hashes) + '\nTRACKS = {\n'
    for key, data in tracks.items():
        rows = data.pop('rows')
        text += repr(key) + ': ' + repr(data)[:-1] + ', "rows": (\n'
        text += ''.join(repr(row) + ',\n' for row in rows)
        text += ')},\n'
    text += '}\n' + RUNTIME
    if len(text.encode()) > 256 * 1024:
        raise ValueError('Generated geometry exceeds per-source limit')
    Path(output).write_text(text)
    print(f'Generated {output}: {len(text.encode())} bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source')
    parser.add_argument('--output', default='track_data.py')
    args = parser.parse_args()
    build(args.source, args.output)
