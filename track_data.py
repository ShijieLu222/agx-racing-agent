from bisect import bisect_right
import math

_STATIONS = {key: tuple(row[0] for row in data["rows"])
             for key, data in TRACKS.items()}


def _track(length):
    if type(length) not in (int, float) or not math.isfinite(length):
        return None
    closest = min(TRACKS.values(), key=lambda t: abs(t["length"] - length))
    # Circuit IDs are absent from some observations. Never guess an unknown map.
    return closest if abs(closest["length"] - length) < 2.0 else None


def geometry_at(track_length_m, s):
    """Return current (curvature, geometric grade, left width, right width).

    Interpolate the actual map station coordinates, including the lap seam.
    A small published-length mismatch is allowed; official_length is never used.
    """
    data = _track(track_length_m)
    if data is None or type(s) not in (int, float) or not math.isfinite(s):
        return None
    position = (s % track_length_m) % data["length"]
    rows, stations = data["rows"], _STATIONS[data["id"]]
    index = bisect_right(stations, position) - 1
    a = rows[index]
    b = rows[(index + 1) % len(rows)]
    end = b[0] if index + 1 < len(rows) else data["length"]
    fraction = (position - a[0]) / max(1e-9, end - a[0])
    return tuple(a[j] + fraction * (b[j] - a[j]) for j in range(1, 5))


def pit_distance(track_length_m, s):
    """Forward arc distance to pit entry, in the observed station coordinates."""
    data = _track(track_length_m)
    if data is None:
        return None
    return (data["pit_entry"] - s) % track_length_m


def aero_remaining(track_length_m, s):
    """Remaining distance in a public X-mode zone, or 0 / unknown None.

    Authoring stations have minor rounding differences from sampled geometry;
    the controller must keep a margin and the platform enforces mechanical gates.
    """
    data = _track(track_length_m)
    if data is None:
        return None
    position = s % track_length_m
    for start, end in data["aero_zones"]:
        span = (end - start) % track_length_m
        progress = (position - start) % track_length_m
        if progress < span:
            return span - progress
    return 0.0
